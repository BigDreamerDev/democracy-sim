/* Identity must not be in the key.

   `subdivisions.json` is keyed by ISO 3166-2, and an ISO 3166-2 code names a
   real place all by itself: `AE-AJ` is Ajman. A map file keyed that way hands
   any player who opens the console the entire real world with no name table
   required — the same invariant `TERRITORY_NAMES` exists to protect, failed
   harder, because names can be moved server-side and keys cannot.

   So the browser, the database and every public response use an opaque id
   (`s0001`). `subdivision-codes.json` holds the pairing, is generated by
   tools/generate-world-subdivisions.py, is append-only, and is never served:
   the only routes that say `AE-AJ` out loud are behind the Returning Officer's
   admin guard, next to the names they already carry. */
let SUBDIVISION_CODES = { ids: {} };
try {
  SUBDIVISION_CODES = require('./subdivision-codes.json');
} catch {
  console.error('[republic] server/subdivision-codes.json is missing — no subdivision may be assigned until it is regenerated');
}
const ID_BY_ISO = SUBDIVISION_CODES.ids || {};
const SUBDIVISION_BY_ID = new Map();
const SUBDIVISIONS_BY_TERRITORY = {};
for (const [country, entries] of Object.entries(SUBDIVISIONS)) {
  const rows = [];
  for (const entry of entries) {
    const id = ID_BY_ISO[entry.code];
    if (!id) continue;
    const row = { code: id, iso: entry.code, name: entry.name || entry.code, type: entry.type || '', country_code: country };
    SUBDIVISION_BY_ID.set(id, row);
    rows.push(row);
  }
  SUBDIVISIONS_BY_TERRITORY[country] = rows;
}
/* Accepts either identifier so a browser holding a cached copy of the old
   client cannot write an ISO code back into the database. */
const subdivisionId = value => {
  const raw = String(value || '').trim();
  if (!raw) return null;
  if (SUBDIVISION_BY_ID.has(raw)) return raw;
  return ID_BY_ISO[raw.toUpperCase()] || null;
};

